package JungSuk;

public class VarEx {
    public static void main(String[] args) {
        int age; // 1. 변수 선언 - 저장 공간 만들기
        age = 10; // 2. 쓰기 - 변수에 값 저장하기
        System.out.println(age); // 3. 읽기 - 변수에 저장된 값 읽어오기
        System.out.println("age = " + age); // soutv
        age = age + 11; // age의 값을 11 증가
        System.out.println("age = " + age); // age.soutv
    }
}
